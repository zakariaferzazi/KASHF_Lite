  String t(String key) {
    final map = _strings[language.code];
    return map?[key] ?? _strings['en']![key] ?? key;
  }

  /// Returns a translated string with simple `{name}` placeholders
  /// replaced by [params]. Unknown placeholders are left as-is.
  String tp(String key, Map<String, String> params) {
    var value = t(key);
    params.forEach((k, v) {
      value = value.replaceAll('{$k}', v);
    });
    return value;
  }

  /// The current [Locale] for Material widgets.
  Locale get locale => Locale(language.code);

  /// Whether the active language is RTL.
  bool get isRtl => language == AppLanguage.arabic;

  /// Look up the localization closest to [context]. Reads from the
  /// nearest [LocaleScope] (which wraps the entire app) and falls back
  /// to a default English instance when no scope is found (e.g., in a
  /// tooltip or test environment).
  static AppLocalizations of(BuildContext context) {
    try {
      final controller = LocaleScope.of(context);
      return AppLocalizations(controller.language);
    } catch (_) {
      return const AppLocalizations(AppLanguage.english);
    }
  }
}

/// Provides translations to the widget tree and flips Material RTL based on
/// the active language.
class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate(this.language);

  final AppLanguage language;

  @override
  bool isSupported(Locale locale) =>
      locale.languageCode == 'en' || locale.languageCode == 'ar';

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(language);

  @override
  bool shouldReload(AppLocalizationsDelegate old) => old.language != language;
}
